#include "libft.h"

char	*ft_strnstr(const char *big, const char *little, size_t len)
{
	size_t	little_len;
	size_t	i;

	little_len = ft_strlen(little);
	if (little_len == 0)
		return ((char *)big);
	i = 0;
	while (i < len && big[i] && little_len <= len - i)
	{
		if (!ft_strncmp(&big[i], little, little_len))
		{
			return ((char *)&big[i]);
		}
		i++;
	}
	return (0);
}
